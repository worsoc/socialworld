package org.socialworld.objects.properties;

/**
 * A simulation object that spoils or wilts in the course of time (food, herbs, flowers).
 * Its current freshness comes with a state later.
 */
public interface IPerishable {

	public static final String NAME = "IPerishable";

	/**
	 * @return how long it keeps, in days
	 */
	public abstract float getShelfLife();

}
